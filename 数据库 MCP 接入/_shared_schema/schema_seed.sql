DROP TABLE IF EXISTS POLICY_SUPPORT;
DROP TABLE IF EXISTS FINANCIAL_METRICS;
DROP TABLE IF EXISTS ENTERPRISES;

CREATE TABLE ENTERPRISES (
  ENTERPRISE_ID INTEGER PRIMARY KEY,
  NAME VARCHAR(100) NOT NULL,
  DISTRICT VARCHAR(100) NOT NULL,
  INDUSTRY VARCHAR(100) NOT NULL,
  ENTERPRISE_SCALE VARCHAR(20) NOT NULL,
  SPECIALIZED_LEVEL VARCHAR(50) NOT NULL,
  REGISTER_CAPITAL_WAN DECIMAL(18, 2),
  FOUNDED_YEAR INTEGER
);

CREATE TABLE FINANCIAL_METRICS (
  METRIC_ID INTEGER PRIMARY KEY,
  ENTERPRISE_ID INTEGER NOT NULL,
  FISCAL_YEAR INTEGER NOT NULL,
  REVENUE_WAN DECIMAL(18, 2) NOT NULL,
  PROFIT_WAN DECIMAL(18, 2) NOT NULL,
  TAX_WAN DECIMAL(18, 2) NOT NULL,
  EMPLOYEE_COUNT INTEGER,
  CONSTRAINT FK_FIN_ENTERPRISE
    FOREIGN KEY (ENTERPRISE_ID) REFERENCES ENTERPRISES (ENTERPRISE_ID)
);

CREATE TABLE POLICY_SUPPORT (
  SUPPORT_ID INTEGER PRIMARY KEY,
  ENTERPRISE_ID INTEGER NOT NULL,
  FISCAL_YEAR INTEGER NOT NULL,
  PROGRAM VARCHAR(100) NOT NULL,
  SUBSIDY_WAN DECIMAL(18, 2) NOT NULL,
  STATUS VARCHAR(30) NOT NULL,
  CONSTRAINT FK_POLICY_ENTERPRISE
    FOREIGN KEY (ENTERPRISE_ID) REFERENCES ENTERPRISES (ENTERPRISE_ID)
);

